//! Linux GL-accelerated video rendering.
//!
//! Uses EGL context sharing between Slint and GStreamer's GL elements
//! (glupload + glcolorconvert) for zero-copy GPU video rendering.

use std::cell::RefCell;
use std::sync::{Arc, Mutex};

use gstreamer as gst;
use gstreamer::prelude::*;
use gstreamer_app as gst_app;
use gstreamer_gl as gst_gl;
use gstreamer_gl::prelude::*;
use gstreamer_gl_egl as gst_gl_egl;
use gstreamer_video as gst_video;
use gst_video::prelude::*;

use chatter_core::services::attachment::CbcRangeDecryptor;
use slint::ComponentHandle;

// Import MainWindow from the crate root (generated by slint::include_modules!)
use crate::MainWindow;

// Global GL video state (must be thread_local for rendering notifier).
thread_local! {
    static GL_VIDEO_STATE: RefCell<Option<GLVideoState>> = const { RefCell::new(None) };
}

/// State for GL video playback.
struct GLVideoState {
    /// AppSink for receiving GL memory samples.
    appsink: gst_app::AppSink,
    /// GL upload element (uploads system memory to GL textures).
    glupload: gst::Element,
    /// GL colorspace converter (YUV -> RGBA on GPU).
    glcolorconvert: gst::Element,
    /// Pipeline for playback.
    pipeline: Option<gst::Pipeline>,
    /// Next frame ready for rendering.
    next_frame: Arc<Mutex<Option<(gst_video::VideoInfo, gst::Buffer)>>>,
    /// GStreamer GL context (wrapped from Slint's EGL context).
    gst_gl_context: Option<gst_gl::GLContext>,
    /// Whether GL is connected.
    connected: bool,
    /// Video duration in ms.
    duration_ms: u64,
    /// Whether playing.
    is_playing: bool,
    /// Audio elements to track for cleanup (prevents multiple audio sources).
    /// Shared Arc so pad-added callback can add elements to this list.
    audio_elements: Arc<Mutex<Vec<gst::Element>>>,
    /// Pending initial volume to apply when audio is ready.
    pending_volume: Option<f64>,
    /// Reused only when GStreamer supplies padded rows.
    staging: Vec<u8>,
    native_size: Arc<Mutex<(u32,u32)>>,
    output_size: (u32,u32),
}

/// Check if GL video is available.
pub fn is_gl_available() -> bool {
    gst::ElementFactory::find("glupload").is_some()
        && gst::ElementFactory::find("glcolorconvert").is_some()
}

/// Check if GL context is connected (ready to play video).
pub fn is_gl_connected() -> bool {
    let connected =
        GL_VIDEO_STATE.with(|cell| cell.borrow().as_ref().map(|s| s.connected).unwrap_or(false));
    tracing::debug!("is_gl_connected() = {}", connected);
    connected
}

/// Initialize GL video rendering for the window.
///
/// Sets up the rendering notifier to fetch GL textures during render.
/// Returns true if GL video was successfully initialized.
pub fn init_gl_video(window: &MainWindow) -> bool {
    // Check for required GL elements
    if gst::ElementFactory::find("glupload").is_none() {
        tracing::info!("GL video not available (glupload not found)");
        return false;
    }

    // The appsink delivers CPU-side RGBA system memory. videoconvert does the
    // YUV->RGBA conversion (correct colorimetry for every stream), and we hand
    // the bytes to the proven manual GL uploader in `gl_call` (glTexImage2D on
    // the render thread, in Slint's own context) instead of GStreamer's
    // glupload/glcolorconvert.
    //
    // The old GPU path (glupload -> glcolorconvert -> GLMemory) rendered solid
    // green for software-decoded AVI: glupload mishandles the padded buffers
    // such decoders emit (see gstreamer bug 729896), so glcolorconvert sampled
    // an empty texture -> YUV(0,0,0) = green. mp4's buffers happen to be tight
    // so the same path worked. The manual uploader is reliable for all formats.
    let appsink = gst_app::AppSink::builder()
        .caps(
            &gst_video::VideoCapsBuilder::new()
                .format(gst_video::VideoFormat::Rgba)
                .build(),
        )
        .enable_last_sample(false)
        .max_buffers(1)
        .build();

    let glupload = match gst::ElementFactory::make("glupload").build() {
        Ok(element) => element,
        Err(e) => {
            tracing::error!("Failed to create glupload: {}", e);
            return false;
        }
    };

    let glcolorconvert = match gst::ElementFactory::make("glcolorconvert").build() {
        Ok(element) => element,
        Err(e) => {
            tracing::error!("Failed to create glcolorconvert: {}", e);
            return false;
        }
    };

    let state = GLVideoState {
        appsink,
        glupload,
        glcolorconvert,
        pipeline: None,
        next_frame: Arc::new(Mutex::new(None)),
        gst_gl_context: None,
        connected: false,
        duration_ms: 0,
        is_playing: false,
        audio_elements: Arc::new(Mutex::new(Vec::new())),
        pending_volume: None,
        staging: Vec::new(),
        native_size: Arc::new(Mutex::new((0,0))),
        output_size: (0,0),
    };

    GL_VIDEO_STATE.with(|cell| {
        *cell.borrow_mut() = Some(state);
    });

    // Set up rendering notifier
    let weak = window.as_weak();
    if let Err(e) = window
        .window()
        .set_rendering_notifier(move |state, graphics_api| {
            crate::record_startup_frame(&state);
            match state {
                slint::RenderingState::RenderingSetup => {
                    tracing::info!("RenderingSetup callback fired - connecting GL context");
                    // Connect GL context when rendering is set up
                    GL_VIDEO_STATE.with(|cell| {
                        if let Some(ref mut video_state) = *cell.borrow_mut() {
                            if let Err(e) = connect_gl_context(video_state, graphics_api) {
                                tracing::warn!("Failed to connect GL context: {}", e);
                            }
                        } else {
                            tracing::warn!("GL_VIDEO_STATE is None in RenderingSetup");
                        }
                    });
                    // Multiplex the single rendering notifier: also load the
                    // call-video GL texture uploader's function table.
                    super::gl_call::on_rendering_setup(graphics_api);
                }
                slint::RenderingState::BeforeRendering => {
                    // Fetch next frame and update video player
                    GL_VIDEO_STATE.with(|cell| {
                        if let Some(ref mut video_state) = *cell.borrow_mut() {
                            if let Some(w) = weak.upgrade() {
                                let size = w.window().size();
                                let native = video_state.native_size.lock().map(|size| *size).unwrap_or((0,0));
                                let output = chatter_core::media::display_frame::fit_dimensions(native.0,native.1,size.width,size.height,true);
                                if output.0 > 0 && output.1 > 0 && output != video_state.output_size {
                                    video_state.appsink.set_caps(Some(&gst_video::VideoCapsBuilder::new()
                                        .format(gst_video::VideoFormat::Rgba)
                                        .width(output.0 as i32).height(output.1 as i32).build()));
                                    video_state.output_size = output;
                                }
                            }
                            if video_state.is_playing {
                                match fetch_next_frame(video_state) {
                                    Some(image) => {
                                        if let Some(w) = weak.upgrade() {
                                            w.global::<crate::ChatPane>()
                                                .set_video_player_frame(image);
                                        }
                                    }
                                    None => {
                                        // Check if there's a frame waiting
                                        let has_pending = video_state
                                            .next_frame
                                            .lock()
                                            .map(|g| g.is_some())
                                            .unwrap_or(false);
                                        if has_pending {
                                            tracing::trace!(
                                                "GL video: frame pending but couldn't be converted"
                                            );
                                        }
                                    }
                                }
                            }
                        }
                    });
                    // Multiplex the notifier: drain the call-video frame inbox and
                    // upload remote participant frames into persistent GL textures
                    // (in-place glTexSubImage2D, no 30 MB Skia copy per frame).
                    if let Some(w) = weak.upgrade() {
                        super::gl_call::on_before_rendering(&w);
                    }
                }
                slint::RenderingState::RenderingTeardown => {
                    // Clean up GL resources
                    GL_VIDEO_STATE.with(|cell| {
                        if let Some(ref mut video_state) = *cell.borrow_mut() {
                            if let Ok(mut next) = video_state.next_frame.lock() {
                                *next = None;
                            }
                            if let Some(ref ctx) = video_state.gst_gl_context {
                                let _ = ctx.activate(false);
                            }
                        }
                    });
                    // Multiplex the notifier: delete all call-video textures.
                    super::gl_call::on_teardown();
                }
                _ => {}
            }
        })
    {
        tracing::error!(
            "Failed to set rendering notifier: {:?} - this prevents hardware video",
            e
        );
        return false;
    }

    tracing::info!(
        "GL video rendering initialized - waiting for first render to connect GL context"
    );
    true
}

/// Connect the GL context from Slint to GStreamer.
fn connect_gl_context(
    state: &mut GLVideoState,
    graphics_api: &slint::GraphicsAPI<'_>,
) -> Result<(), String> {
    tracing::info!(
        "connect_gl_context called, already connected: {}",
        state.connected
    );
    if state.connected {
        return Ok(());
    }

    // Load EGL functions
    let egl = match graphics_api {
        slint::GraphicsAPI::NativeOpenGL { get_proc_address } => {
            tracing::info!("Graphics API is NativeOpenGL - loading EGL functions");
            glutin_egl_sys::egl::Egl::load_with(|symbol| {
                get_proc_address(&std::ffi::CString::new(symbol).unwrap())
            })
        }
        _ => {
            tracing::error!("Graphics API is NOT NativeOpenGL - cannot use hardware video");
            return Err("Unsupported graphics API - requires OpenGL".to_string());
        }
    };

    // Wrap Slint's EGL context for GStreamer
    let (gst_gl_context, _gst_gl_display) = unsafe {
        let platform = gst_gl::GLPlatform::EGL;
        let egl_display = egl.GetCurrentDisplay();
        let native_context = egl.GetCurrentContext();

        tracing::info!(
            "EGL display: {:?}, context: {:?}",
            egl_display,
            native_context
        );

        if egl_display.is_null() {
            return Err("EGL display is null - no current display".to_string());
        }
        if native_context.is_null() {
            return Err("EGL context is null - no current context".to_string());
        }

        let display = gst_gl_egl::GLDisplayEGL::with_egl_display(egl_display as usize)
            .map_err(|e| format!("Failed to wrap EGL display: {}", e))?;

        let gl_api = gst_gl::GLContext::current_gl_api(platform);
        tracing::info!("Current GL API: {:?}", gl_api);

        let context =
            gst_gl::GLContext::new_wrapped(&display, native_context as _, platform, gl_api.0)
                .ok_or_else(|| {
                    "Failed to wrap GL context - GLContext::new_wrapped returned None".to_string()
                })?;

        (context, display)
    };

    // Activate and fill context info
    gst_gl_context
        .activate(true)
        .map_err(|e| format!("Failed to activate GL context: {}", e))?;
    gst_gl_context
        .fill_info()
        .map_err(|e| format!("Failed to fill GL info: {}", e))?;

    state.gst_gl_context = Some(gst_gl_context.clone());
    state.connected = true;
    tracing::info!("GL context connected successfully - hardware video ready");

    // Set up frame arrival callback
    // Track frame count for debugging
    let frame_count = Arc::new(std::sync::atomic::AtomicU64::new(0));
    let frame_count_clone = frame_count.clone();
    let next_frame = state.next_frame.clone();
    state.appsink.set_callbacks(
        gst_app::AppSinkCallbacks::builder()
            .new_sample(move |appsink| {
                let sample = appsink
                    .pull_sample()
                    .map_err(|_| gst::FlowError::Flushing)?;
                let buffer = sample.buffer_owned().unwrap();

                // Increment frame count and log occasionally
                let count = frame_count_clone.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                if count == 0 {
                    tracing::info!("GL video: first frame received from appsink");
                } else if count % 300 == 0 {
                    tracing::debug!("GL video: {} frames received", count);
                }

                // System-memory RGBA. The actual GPU upload happens on the
                // render thread in fetch_next_frame (gl_call manual uploader).
                let info = sample
                    .caps()
                    .and_then(|caps| gst_video::VideoInfo::from_caps(caps).ok())
                    .ok_or(gst::FlowError::NotNegotiated)?;

                *next_frame.lock().unwrap() = Some((info, buffer));

                Ok(gst::FlowSuccess::Ok)
            })
            .build(),
    );

    tracing::info!("GL context connected for video rendering");
    Ok(())
}

/// Fetch the next frame and upload it to a GL texture for rendering.
///
/// Runs on the render thread (Slint's BeforeRendering notifier). Maps the
/// system-memory RGBA buffer the appsink delivered, repacks it tightly (the
/// buffer may carry stride padding), and uploads it via the proven `gl_call`
/// manual uploader, returning a `BorrowedOpenGLTexture` Slint image.
fn fetch_next_frame(state: &mut GLVideoState) -> Option<slint::Image> {
    // Track frame statistics for debugging
    static FRAME_FETCH_COUNT: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);

    let (info, buffer) = state.next_frame.lock().ok()?.take()?;
    let count = FRAME_FETCH_COUNT.fetch_add(1, std::sync::atomic::Ordering::Relaxed);

    let width = info.width();
    let height = info.height();
    if count == 0 {
        tracing::info!(
            "GL video: first frame fetched for rendering, size: {}x{}",
            width,
            height
        );
    }

    // Map the RGBA frame and copy into a tightly-packed buffer (stride == w*4),
    // honoring the source stride which may be padded.
    let vframe = gst_video::VideoFrameRef::from_buffer_ref_readable(buffer.as_ref(), &info).ok()?;
    let src = vframe.plane_data(0).ok()?;
    let src_stride = vframe.plane_stride()[0] as usize;
    let row_bytes = (width as usize) * 4;
    let required = row_bytes.checked_mul(height as usize)?;
    if src_stride == row_bytes && src.len() >= required {
        return super::gl_call::upload_media_player_frame(&src[..required], width, height);
    }
    state.staging.resize(required, 0);
    let tight = &mut state.staging;
    for y in 0..height as usize {
        let s = y * src_stride;
        let d = y * row_bytes;
        if s + row_bytes > src.len() {
            return None;
        }
        tight[d..d + row_bytes].copy_from_slice(&src[s..s + row_bytes]);
    }

    super::gl_call::upload_media_player_frame(tight, width, height)
}

/// Start playing video from memory using GL rendering.
///
/// Returns the duration in seconds, or None if GL video is not available.
/// Backing byte source for the video AppSrc.
///
/// `Memory` is a fully-decrypted buffer (small/legacy path). `Range` pulls
/// decrypted plaintext on demand from an already-authenticated CBC attachment,
/// so playback starts without decrypting the whole file up front.
pub enum VideoSource {
    Memory(Arc<Vec<u8>>),
    Range(Arc<CbcRangeDecryptor>),
}

impl VideoSource {
    fn total_len(&self) -> usize {
        match self {
            VideoSource::Memory(d) => d.len(),
            VideoSource::Range(r) => r.plaintext_size(),
        }
    }

    /// Read up to `len` plaintext bytes at `off` (fewer at EOF).
    fn read(&self, off: usize, len: usize) -> Vec<u8> {
        match self {
            VideoSource::Memory(d) => {
                if off >= d.len() {
                    return Vec::new();
                }
                let end = (off + len).min(d.len());
                d[off..end].to_vec()
            }
            VideoSource::Range(r) => r.read_range(off, len),
        }
    }
}

/// Start GL video from a fully-decrypted in-memory buffer.
pub fn start_gl_video(data: Vec<u8>) -> Option<f64> {
    start_gl_video_source(VideoSource::Memory(Arc::new(data)))
}

/// Start GL video from an authenticated random-access CBC decryptor (streaming).
pub fn start_gl_video_range(dec: Arc<CbcRangeDecryptor>) -> Option<f64> {
    start_gl_video_source(VideoSource::Range(dec))
}

fn start_gl_video_source(source: VideoSource) -> Option<f64> {
    GL_VIDEO_STATE.with(|cell| {
        let mut state_ref = cell.borrow_mut();
        let state = state_ref.as_mut()?;

        if !state.connected {
            tracing::warn!("GL context not connected yet");
            return None;
        }

        // Stop any existing pipeline - full cleanup to prevent multiple audio sources
        if let Some(pipeline) = state.pipeline.take() {
            tracing::info!("GL video: stopping previous pipeline before starting new one");

            // First set pipeline to NULL
            let _ = pipeline.set_state(gst::State::Null);
            // Wait for cleanup to complete
            let _ = pipeline.state(gst::ClockTime::from_seconds(1));

            // Explicitly stop all elements
            for element in pipeline.iterate_elements().into_iter().flatten() {
                let _ = element.set_state(gst::State::Null);
            }

            // CRITICAL: Remove GL elements so they can be reused in new pipeline
            let _ = pipeline.remove(&state.glupload);
            let _ = pipeline.remove(&state.glcolorconvert);
            let _ = pipeline.remove(&state.appsink);
            let _ = state.glupload.set_state(gst::State::Null);
            let _ = state.glcolorconvert.set_state(gst::State::Null);
            let _ = state.appsink.set_state(gst::State::Null);

            // CRITICAL: Explicitly clean up audio elements to prevent multiple PipeWire streams
            if let Ok(mut audio_elements) = state.audio_elements.lock() {
                tracing::info!("GL video: cleaning up {} audio elements", audio_elements.len());
                for element in audio_elements.drain(..) {
                    let name = element.name().to_string();
                    let _ = pipeline.remove(&element);
                    let _ = element.set_state(gst::State::Null);
                    tracing::debug!("GL video: removed audio element '{}'", name);
                }
            }

            tracing::info!("GL video: previous pipeline cleaned up");
        } else {
            // No previous pipeline, but still clear any stale audio element refs
            if let Ok(mut audio_elements) = state.audio_elements.lock() {
                audio_elements.clear();
            }
        }

        // Create new pipeline
        let pipeline = gst::Pipeline::new();

        // Create appsrc backed by `source` (in-memory buffer or on-demand range
        // decryptor). RandomAccess so decodebin can seek (e.g. AVI index at the
        // file tail) without reading the whole stream.
        let total_len = source.total_len();
        let appsrc = gst_app::AppSrc::builder()
            .stream_type(gst_app::AppStreamType::RandomAccess)
            .size(total_len as i64)
            .format(gst::Format::Bytes)
            .build();

        // Set up data feeding
        let source = Arc::new(source);
        let source_need = source.clone();
        let source_seek = source.clone();
        let read_pos = Arc::new(Mutex::new(0usize));
        let read_pos_need = read_pos.clone();
        let read_pos_seek = read_pos.clone();

        appsrc.set_callbacks(
            gst_app::AppSrcCallbacks::builder()
                .need_data(move |appsrc, hint| {
                    let mut pos = read_pos_need.lock().unwrap();

                    if *pos >= total_len {
                        let _ = appsrc.end_of_stream();
                        return;
                    }

                    let want = if hint > 0 {
                        std::cmp::min(hint as usize, total_len - *pos)
                    } else {
                        std::cmp::min(65536, total_len - *pos)
                    };

                    let offset = *pos as u64;
                    let chunk = source_need.read(*pos, want);
                    let n = chunk.len();
                    if n == 0 {
                        let _ = appsrc.end_of_stream();
                        return;
                    }

                    let mut buffer = gst::Buffer::from_slice(chunk);
                    {
                        let buffer_ref = buffer.get_mut().unwrap();
                        buffer_ref.set_offset(offset);
                        buffer_ref.set_offset_end(offset + n as u64);
                    }

                    if appsrc.push_buffer(buffer).is_err() {
                        return;
                    }

                    *pos += n;
                })
                .seek_data(move |_appsrc, offset| {
                    let offset_usize = offset as usize;
                    if offset_usize > source_seek.total_len() {
                        return false;
                    }
                    *read_pos_seek.lock().unwrap() = offset_usize;
                    true
                })
                .build()
        );

        // Create decodebin3 with proper stream selection
        // decodebin3 requires us to select which streams to decode
        let decodebin = gst::ElementFactory::make("decodebin3")
            .build()
            .ok()?;

        // Handle stream selection - select ALL audio and video streams
        // Signal signature: (element, collection, stream) -> gint
        // Return values: 1 = select, 0 = don't select, -1 = let decodebin decide
        decodebin.connect("select-stream", false, |args| {
            let _decodebin = args[0].get::<gst::Element>().unwrap();
            let _collection = args[1].get::<gst::StreamCollection>().unwrap();
            let stream = args[2].get::<gst::Stream>().unwrap();
            let stream_type = stream.stream_type();

            // Select both audio and video streams
            let dominated = stream_type.contains(gst::StreamType::AUDIO)
                || stream_type.contains(gst::StreamType::VIDEO);

            if dominated {
                tracing::debug!("decodebin3: selecting stream {:?} (type: {:?})",
                    stream.stream_id(), stream_type);
            }

            // Return gint: 1 = select, 0 = don't select, -1 = let decodebin decide
            Some((if dominated { 1i32 } else { 0i32 }).to_value())
        });

        // Add elements to pipeline
        pipeline.add_many([appsrc.upcast_ref(), &decodebin]).ok()?;
        appsrc.link(&decodebin).ok()?;

        // Track when video sink is linked (for waiting)
        let video_linked = Arc::new(std::sync::atomic::AtomicBool::new(false));
        let video_linked_clone = video_linked.clone();

        // Handle decodebin pad-added - connect both video AND audio
        let appsink_clone = state.appsink.clone();
        let pipeline_weak = pipeline.downgrade();
        let audio_elements_arc = state.audio_elements.clone();
        let native_size = state.native_size.clone();
        state.output_size = (0,0);
        if let Ok(mut size) = state.native_size.lock() { *size = (0,0); }
        state.appsink.set_caps(Some(&gst_video::VideoCapsBuilder::new().format(gst_video::VideoFormat::Rgba).build()));
        decodebin.connect_pad_added(move |_decodebin, src_pad| {
            let caps = src_pad.current_caps().or_else(|| Some(src_pad.query_caps(None)));
            if let Some(caps) = caps {
                let structure = caps.structure(0);
                if let Some(s) = structure {
                    let name = s.name().as_str();
                    tracing::info!("Decodebin pad-added: {} (caps: {})", name, caps.to_string());

                    if name.starts_with("video/") {
                        if let Ok(mut size) = native_size.lock() {
                            *size = (s.get::<i32>("width").unwrap_or(0).max(0) as u32,
                                     s.get::<i32>("height").unwrap_or(0).max(0) as u32);
                        }
                        if let Some(pipeline) = pipeline_weak.upgrade() {
                            // Add queue + videoconvert before GL elements.
                            // videoconvert is CRITICAL: AVI codecs (MPEG-4 Part 2, DivX, etc.)
                            // often decode to formats like YV12/BGR that glupload can't accept
                            // directly, while MKV's H.264 decodes to NV12/I420 which glupload
                            // handles natively. videoconvert bridges the gap for all formats.
                            // queue decouples the decoder thread from the GL sink thread.
                            let queue = match gst::ElementFactory::make("queue")
                                .property("max-size-buffers", 10u32)
                                .property("max-size-time", 500_000_000u64)
                                .build()
                            {
                                Ok(e) => e,
                                Err(e) => {
                                    tracing::error!("GL video: failed to create video queue: {}", e);
                                    return;
                                }
                            };
                            let videoconvert = match gst::ElementFactory::make("videoconvert").build() {
                                Ok(e) => e,
                                Err(e) => {
                                    tracing::error!("GL video: failed to create videoconvert: {}", e);
                                    return;
                                }
                            };

                            // Force videoconvert to emit tightly-packed system-memory RGBA.
                            // The appsink delivers these bytes to the render thread, where
                            // gl_call uploads them to a GL texture manually (reliable for the
                            // padded software-decoded buffers that broke glupload).
                            let rgba_filter = match gst::ElementFactory::make("capsfilter")
                                .property(
                                    "caps",
                                    gst_video::VideoCapsBuilder::new()
                                        .format(gst_video::VideoFormat::Rgba)
                                        .build(),
                                )
                                .build()
                            {
                                Ok(e) => e,
                                Err(e) => {
                                    tracing::error!("GL video: failed to create rgba capsfilter: {}", e);
                                    return;
                                }
                            };

                            let videoscale = match gst::ElementFactory::make("videoscale").build() {
                                Ok(scale) => scale,
                                Err(error) => { tracing::error!(%error, "GL video: videoscale unavailable"); return; }
                            };
                            let appsink_element: &gst::Element = appsink_clone.upcast_ref();
                            let elements: &[&gst::Element] = &[
                                &queue,
                                &videoconvert,
                                &videoscale,
                                &rgba_filter,
                                appsink_element,
                            ];

                            if let Err(e) = pipeline.add_many(elements) {
                                tracing::error!("GL video: failed to add video elements: {:?}", e);
                                return;
                            }

                            if let Err(e) = gst::Element::link_many(elements) {
                                tracing::error!("GL video: failed to link video elements: {:?}", e);
                                return;
                            }

                            // Sync state with parent before linking to decodebin
                            for e in elements {
                                e.sync_state_with_parent().ok();
                            }

                            // Link decodebin output to queue input
                            if let Some(sink_pad) = queue.static_pad("sink") {
                                if let Err(e) = src_pad.link(&sink_pad) {
                                    tracing::error!("GL video: failed to link decodebin to queue: {:?}", e);
                                    return;
                                }
                                video_linked_clone.store(true, std::sync::atomic::Ordering::SeqCst);
                                tracing::info!("GL video pipeline linked: decodebin -> queue -> videoconvert -> RGBA -> appsink (manual GL upload)");
                            }
                        }
                    } else if name.starts_with("audio/") {
                        // Create audio pipeline: queue -> audioconvert -> audioresample -> volume -> autoaudiosink
                        // Queue decouples streaming thread from audio sink (allows async state transitions)
                        if let Some(pipeline) = pipeline_weak.upgrade() {
                            let audio_elements_clone = audio_elements_arc.clone();
                            let create_audio = || -> Result<(), String> {
                                tracing::info!("GL video: creating audio pipeline for caps: {}", caps.to_string());

                                // Queue provides buffering and thread decoupling (critical for dynamic pipelines)
                                let queue = gst::ElementFactory::make("queue")
                                    .name("audio-queue")
                                    .property("max-size-time", 1_000_000_000u64) // 1 second buffer
                                    .build()
                                    .map_err(|e| format!("queue: {}", e))?;

                                // audioconvert handles planar->interleaved conversion automatically
                                let convert = gst::ElementFactory::make("audioconvert")
                                    .build()
                                    .map_err(|e| format!("audioconvert: {}", e))?;
                                let resample = gst::ElementFactory::make("audioresample")
                                    .build()
                                    .map_err(|e| format!("audioresample: {}", e))?;
                                let volume = gst::ElementFactory::make("volume")
                                    .name("audio-volume")
                                    .property("volume", 1.0f64)
                                    .build()
                                    .map_err(|e| format!("volume: {}", e))?;

                                // Use autoaudiosink - more robust than pulsesink for dynamic pipelines
                                let sink = if chatter_core::system::null_audio() {
                                    "fakesink"
                                } else {
                                    "autoaudiosink"
                                };
                                let audiosink = gst::ElementFactory::make(sink)
                                    .name("audio-sink")
                                    .build()
                                    .map_err(|e| format!("{sink}: {e}"))?;

                                let elements: &[&gst::Element] = &[&queue, &convert, &resample, &volume, &audiosink];
                                pipeline.add_many(elements)
                                    .map_err(|e| format!("add_many: {}", e))?;
                                gst::Element::link_many(elements)
                                    .map_err(|e| format!("link_many: {}", e))?;

                                // Sync state with parent BEFORE linking to decodebin
                                // (same pattern as software decoder)
                                for e in elements {
                                    e.sync_state_with_parent()
                                        .map_err(|e| format!("sync_state: {}", e))?;
                                }

                                // Link decodebin pad to queue's sink
                                let sink_pad = queue.static_pad("sink")
                                    .ok_or_else(|| "No sink pad on queue".to_string())?;

                                let link_result = src_pad.link(&sink_pad);
                                tracing::info!("GL video: audio pad link result: {:?}", link_result);
                                link_result.map_err(|e| format!("link: {:?}", e))?;

                                // CRITICAL: Track audio elements for cleanup to prevent multiple PipeWire streams
                                if let Ok(mut audio_vec) = audio_elements_clone.lock() {
                                    audio_vec.push(queue.clone());
                                    audio_vec.push(convert.clone());
                                    audio_vec.push(resample.clone());
                                    audio_vec.push(volume.clone());
                                    audio_vec.push(audiosink.clone());
                                    tracing::info!("GL video: tracking {} audio elements for cleanup", audio_vec.len());
                                }

                                // Log element states for debugging
                                tracing::info!(
                                    "GL video audio: pipeline_state={:?}, convert={:?}, sink={:?}",
                                    pipeline.current_state(),
                                    convert.current_state(),
                                    audiosink.current_state()
                                );

                                tracing::info!("GL video audio pipeline linked successfully");
                                Ok(())
                            };

                            if let Err(e) = create_audio() {
                                tracing::warn!("Failed to create audio pipeline: {}", e);
                            }
                        }
                    }
                }
            }
        });

        // Set up bus handler for GL context messages
        // GL elements (glupload, glcolorconvert) need both the GL context and the GL display
        if let Some(bus) = pipeline.bus() {
            let gst_gl_context = state.gst_gl_context.clone();
            bus.set_sync_handler(move |_, msg| {
                if let gst::MessageView::NeedContext(ctx) = msg.view() {
                    let ctx_type = ctx.context_type();

                    if let Some(element) = msg.src().and_then(|s| s.downcast_ref::<gst::Element>()) {
                        if let Some(ref gl_ctx) = gst_gl_context {
                            if ctx_type == "gst.gl.app_context" {
                                // Provide the GL context wrapper
                                let mut gst_context = gst::Context::new(ctx_type, true);
                                {
                                    let gst_context = gst_context.get_mut().unwrap();
                                    let structure = gst_context.structure_mut();
                                    structure.set("context", gl_ctx);
                                }
                                element.set_context(&gst_context);
                                tracing::debug!("Provided gst.gl.app_context to {}", element.name());
                            } else if ctx_type == "gst.gl.GLDisplay" {
                                // Provide the GL display from our context
                                let display = gl_ctx.display();
                                let mut gst_context = gst::Context::new(ctx_type, true);
                                {
                                    let gst_context = gst_context.get_mut().unwrap();
                                    let structure = gst_context.structure_mut();
                                    structure.set("gst.gl.GLDisplay", &display);
                                }
                                element.set_context(&gst_context);
                                tracing::debug!("Provided gst.gl.GLDisplay to {}", element.name());
                            }
                        }
                    }
                    // Drop handled GL context messages
                    return gst::BusSyncReply::Drop;
                }
                // Pass through all other messages (errors, warnings, state changes)
                // so the error-checking loop can see them
                gst::BusSyncReply::Pass
            });
        }

        // Start pipeline in PAUSED first to allow preroll
        pipeline.set_state(gst::State::Paused).ok()?;

        // Wait for video sink to be linked (decodebin pad-added runs asynchronously)
        let timeout = std::time::Instant::now() + std::time::Duration::from_secs(10);
        while std::time::Instant::now() < timeout {
            if video_linked.load(std::sync::atomic::Ordering::SeqCst) {
                // Give more time for audio pad to be added (demuxer processes streams sequentially)
                // Audio pad typically comes shortly after video pad
                std::thread::sleep(std::time::Duration::from_millis(500));
                break;
            }

            // Check for pipeline errors while waiting
            if let Some(bus) = pipeline.bus() {
                while let Some(msg) = bus.pop() {
                    if let gst::MessageView::Error(err) = msg.view() {
                        tracing::error!("GL video pipeline error: {} ({:?})", err.error(), err.debug());
                        pipeline.set_state(gst::State::Null).ok();
                        return None;
                    }
                }
            }

            std::thread::sleep(std::time::Duration::from_millis(50));
        }

        if !video_linked.load(std::sync::atomic::Ordering::SeqCst) {
            tracing::error!("GL video: timeout waiting for video sink to link");
            pipeline.set_state(gst::State::Null).ok();
            return None;
        }

        // Now set to PLAYING - this also triggers audio to start
        pipeline.set_state(gst::State::Playing).ok()?;

        // Wait for state change and query duration
        let _ = pipeline.state(gst::ClockTime::from_seconds(5));

        // Query duration - may need to retry as demuxer parses
        let mut duration = 0.0;
        for _ in 0..10 {
            if let Some(dur) = pipeline.query_duration::<gst::ClockTime>() {
                duration = dur.mseconds() as f64 / 1000.0;
                if duration > 0.0 {
                    break;
                }
            }
            std::thread::sleep(std::time::Duration::from_millis(100));
        }

        state.pipeline = Some(pipeline);
        state.duration_ms = (duration * 1000.0) as u64;
        state.is_playing = true;

        tracing::info!("GL video started, duration: {}s", duration);
        Some(duration)
    })
}

/// Stop GL video playback.
pub fn stop_gl_video() {
    GL_VIDEO_STATE.with(|cell| {
        if let Some(ref mut state) = *cell.borrow_mut() {
            // Take ownership of pipeline to ensure proper cleanup
            if let Some(pipeline) = state.pipeline.take() {
                tracing::debug!("GL video: stopping pipeline...");

                // First set pipeline to NULL - this propagates to all children
                let _ = pipeline.set_state(gst::State::Null);

                // Wait for state change to complete (prevents "disposing in PLAYING" warnings)
                let _ = pipeline.state(gst::ClockTime::from_seconds(2));

                // Explicitly stop all elements to be safe (per GStreamer cleanup best practices)
                for element in pipeline.iterate_elements().into_iter().flatten() {
                    let _ = element.set_state(gst::State::Null);
                }

                // CRITICAL: Remove GL elements from pipeline so they can be reused in next playback
                // Without this, adding them to a new pipeline will silently fail
                let _ = pipeline.remove(&state.glupload);
                let _ = pipeline.remove(&state.glcolorconvert);
                let _ = pipeline.remove(&state.appsink);
                let _ = state.glupload.set_state(gst::State::Null);
                let _ = state.glcolorconvert.set_state(gst::State::Null);
                let _ = state.appsink.set_state(gst::State::Null);

                // CRITICAL: Explicitly clean up audio elements to prevent multiple PipeWire streams
                if let Ok(mut audio_elements) = state.audio_elements.lock() {
                    tracing::info!(
                        "GL video stop: cleaning up {} audio elements",
                        audio_elements.len()
                    );
                    for element in audio_elements.drain(..) {
                        let name = element.name().to_string();
                        let _ = pipeline.remove(&element);
                        let _ = element.set_state(gst::State::Null);
                        tracing::debug!("GL video stop: removed audio element '{}'", name);
                    }
                }

                tracing::debug!("GL video: pipeline stopped and cleaned up");
            }
            state.is_playing = false;
            state.duration_ms = 0;
            state.pending_volume = None;
            if let Ok(mut next) = state.next_frame.lock() {
                *next = None;
            }
        }
    });
}

/// Pause/resume GL video.
pub fn set_gl_video_playing(playing: bool) {
    GL_VIDEO_STATE.with(|cell| {
        if let Some(ref mut state) = *cell.borrow_mut() {
            state.is_playing = playing;
            if let Some(ref pipeline) = state.pipeline {
                if playing {
                    let _ = pipeline.set_state(gst::State::Playing);
                } else {
                    let _ = pipeline.set_state(gst::State::Paused);
                }
            }
        }
    });
}

/// Get current GL video position in seconds.
pub fn get_gl_video_position() -> Option<f64> {
    GL_VIDEO_STATE.with(|cell| {
        let state_ref = cell.borrow();
        let state = state_ref.as_ref()?;
        let pipeline = state.pipeline.as_ref()?;
        pipeline
            .query_position::<gst::ClockTime>()
            .map(|p| p.mseconds() as f64 / 1000.0)
    })
}

/// Seek GL video to position in seconds.
pub fn seek_gl_video(position: f64) {
    GL_VIDEO_STATE.with(|cell| {
        if let Some(ref mut state) = *cell.borrow_mut() {
            if let Some(ref pipeline) = state.pipeline {
                let pos_ns = (position * 1_000_000_000.0) as u64;
                let duration_ns = (state.duration_ms as u64) * 1_000_000;

                // Clamp position to valid range
                let clamped_ns = pos_ns.min(duration_ns);
                let seek_pos = gst::ClockTime::from_nseconds(clamped_ns);

                tracing::debug!("GL video seeking to {}s", position);

                // Clear pending frame so we get a fresh frame after seek
                if let Ok(mut next) = state.next_frame.lock() {
                    *next = None;
                }

                // Use seek_simple for reliability across different container formats
                // FLUSH: Flush pipeline before seeking (required for responsive seek)
                // KEY_UNIT: Seek to nearest keyframe (faster, works with most formats)
                // NOTE: TRICKMODE removed - causes issues with some MP4 files
                if let Err(e) =
                    pipeline.seek_simple(gst::SeekFlags::FLUSH | gst::SeekFlags::KEY_UNIT, seek_pos)
                {
                    tracing::error!("GL video seek failed: {:?}", e);
                    return;
                }

                // Wait briefly for seek to complete
                let _ = pipeline.state(gst::ClockTime::from_mseconds(100));

                // Ensure pipeline resumes to correct state after seek
                let target_state = if state.is_playing {
                    gst::State::Playing
                } else {
                    gst::State::Paused
                };
                if let Err(e) = pipeline.set_state(target_state) {
                    tracing::error!("Failed to set state after seek: {:?}", e);
                }

                tracing::debug!("GL video seek completed");
            }
        }
    });
}

/// Set GL video volume (0.0 - 1.0).
pub fn set_gl_video_volume(volume: f64) {
    GL_VIDEO_STATE.with(|cell| {
        if let Some(ref mut state) = *cell.borrow_mut() {
            let clamped = volume.clamp(0.0, 1.0);

            if let Some(ref pipeline) = state.pipeline {
                // Find the named volume element we added to the audio pipeline
                if let Some(volume_element) = pipeline.by_name("audio-volume") {
                    volume_element.set_property("volume", clamped);
                    tracing::debug!("GL video volume set to {:.2}", clamped);
                    state.pending_volume = None; // Volume applied, clear pending
                } else {
                    // Audio pipeline not ready yet - store for later
                    tracing::debug!(
                        "GL video: volume element not found, storing pending volume {:.2}",
                        clamped
                    );
                    state.pending_volume = Some(clamped);
                }
            } else {
                // No pipeline yet, store for when it's created
                state.pending_volume = Some(clamped);
            }
        }
    });
}

/// Apply pending volume if audio is now ready (called periodically during playback).
pub fn apply_pending_volume() {
    GL_VIDEO_STATE.with(|cell| {
        if let Some(ref mut state) = *cell.borrow_mut() {
            if let Some(pending_vol) = state.pending_volume {
                if let Some(ref pipeline) = state.pipeline {
                    if let Some(volume_element) = pipeline.by_name("audio-volume") {
                        volume_element.set_property("volume", pending_vol);
                        tracing::debug!("GL video: applied pending volume {:.2}", pending_vol);
                        state.pending_volume = None;
                    }
                }
            }
        }
    });
}

/// Check if GL video is currently playing.
pub fn is_gl_video_active() -> bool {
    GL_VIDEO_STATE.with(|cell| {
        cell.borrow()
            .as_ref()
            .map(|s| s.pipeline.is_some() && s.is_playing)
            .unwrap_or(false)
    })
}

/// Get GL video duration in seconds.
pub fn get_gl_video_duration() -> Option<f64> {
    GL_VIDEO_STATE.with(|cell| {
        cell.borrow()
            .as_ref()
            .filter(|s| s.duration_ms > 0)
            .map(|s| s.duration_ms as f64 / 1000.0)
    })
}
