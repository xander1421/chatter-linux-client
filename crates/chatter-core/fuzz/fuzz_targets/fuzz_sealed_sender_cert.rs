#![no_main]
//! Fuzz target: sealed sender certificate deserialization + trust-root
//! validation.
//!
//! Property: feeding random bytes into the sealed-sender cert path must:
//!   1. NEVER panic.
//!   2. Either fail to deserialize (Err from `SenderCertificate::deserialize`)
//!      OR, if it somehow deserializes, fail trust-root validation
//!      (`validate_trust_root` returns `false`). Random bytes cannot produce a
//!      valid Ed25519 signature against the hardcoded trust root.
//!
//! Public API surface used:
//!   - `chatter_core::crypto::signal::SenderCertificate` (re-export of
//!     libsignal's type)
//!   - `chatter_core::crypto::signal::sealed_sender::validate_trust_root`
//!     (free function in a `pub mod` chain — reachable through public API).
//!
//! Note: `validate_trust_root` is the chatter-specific wrapper that pins
//! the cert against the binary-baked `TRUST_ROOT_PUBLIC_KEY`. We hit it
//! through the public path, which is exactly what production code does.

use libfuzzer_sys::fuzz_target;

use chatter_core::crypto::signal::SenderCertificate;
use chatter_core::crypto::signal::sealed_sender::validate_trust_root;

fuzz_target!(|data: &[u8]| {
    // Step 1: try to deserialize. Must not panic on any input.
    let cert = match SenderCertificate::deserialize(data) {
        Ok(c) => c,
        Err(_) => {
            // Expected path for malformed bytes — done.
            return;
        }
    };

    // Step 2: if deserialize miraculously succeeded on random bytes, the cert
    // still must NOT pass trust-root validation. The trust root is a fixed
    // Ed25519 public key compiled into the binary; random Ed25519 signatures
    // from random bytes verify with negligible probability.
    let valid = validate_trust_root(&cert);

    // Property: validate_trust_root returns false (or, if it returned true,
    // the fuzzer just found either (a) a forgery against our trust root, or
    // (b) a libsignal validation bug). Either is a finding.
    assert!(
        !valid,
        "validate_trust_root returned true on a SenderCertificate \
         deserialized from fuzzer-generated bytes — investigate"
    );
});
