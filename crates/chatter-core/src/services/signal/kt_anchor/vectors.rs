use std::collections::HashMap;
use std::time::{Duration, SystemTime};

use base64::Engine as _;
use chatter_proto::chat_v1::KtSearchResponse;
use libsignal_keytrans::{
    CondensedTreeSearchResponse, DeploymentMode, FullSearchResponse, FullTreeHead, KeyTransparency,
    LastTreeHead, MonitorContext, MonitorRequest, MonitorResponse, MonitoringData, PublicConfig,
    SearchContext, SlimSearchRequest, VerifyingKey, VrfPublicKey,
};
use prost::Message;
use serde::Deserialize;

#[derive(Deserialize)]
struct Vector {
    name: String,
    label: Option<String>,
    version: Option<u32>,
    last: Option<String>,
    distinguished: Option<String>,
    data: Option<String>,
    monitor: Option<String>,
    proof: Option<String>,
    value: Option<String>,
    #[serde(default)]
    reject: bool,
}

fn bytes(encoded: &str) -> Vec<u8> {
    base64::engine::general_purpose::STANDARD
        .decode(encoded)
        .unwrap()
}

/// Generated by TestLibsignalVectors in the Go keytransparency service.
#[test]
fn go_proofs_verify_with_libsignal() {
    let key = |hex| <[u8; 32]>::try_from(hex::decode(hex).unwrap()).unwrap();
    let verifier = KeyTransparency {
        config: PublicConfig {
            mode: DeploymentMode::ContactMonitoring,
            signature_key: VerifyingKey::from_bytes(&key(
                "3b6a27bcceb6a42d62a3a8d02a6f0d73653215771de243a63ac048a18b59da29",
            ))
            .unwrap(),
            vrf_key: VrfPublicKey::try_from(key(
                "48af975feaba33ea110d4ab0c8f7a38c5c7122db185ff9499b81e5e74da6ec47",
            ))
            .unwrap(),
        },
    };
    let archive = flate2::read::GzDecoder::new(&include_bytes!("libsignal-vectors.json.gz")[..]);
    let vectors: Vec<Vector> = serde_json::from_reader(archive).unwrap();
    let now = SystemTime::UNIX_EPOCH + Duration::from_millis(1_800_000_000_100);
    let mut heads: HashMap<String, LastTreeHead> = HashMap::new();
    let mut observations: HashMap<String, (Vec<u8>, MonitoringData)> = HashMap::new();
    for vector in vectors {
        let Vector {
            name,
            label,
            version,
            last,
            distinguished,
            data,
            monitor,
            proof,
            value,
            reject,
        } = vector;
        let Some(proof) = proof else {
            assert!(value.is_none() && monitor.is_none() && !reject, "{name}");
            continue; // The Go producer returned NotFound; there is no libsignal absence proof.
        };
        let proof = bytes(&proof);
        let last = last.as_ref().map(|name| &heads[name]);
        let distinguished = distinguished.as_ref().map(|name| &heads[name]);
        if let Some(request) = monitor {
            let request = MonitorRequest::decode(bytes(&request).as_slice()).unwrap();
            let response = MonitorResponse::decode(proof.as_slice()).unwrap();
            let monitor_data = data
                .unwrap()
                .split(':')
                .map(|name| observations[name].clone())
                .collect();
            let result = verifier.verify_monitor(
                &request,
                &response,
                MonitorContext {
                    last_tree_head: last,
                    last_distinguished_tree_head: distinguished.unwrap(),
                    data: monitor_data,
                },
                now,
            );
            if reject {
                assert!(result.is_err(), "{name} unexpectedly verified");
            } else {
                let state = result.unwrap_or_else(|error| panic!("{name}: {error}"));
                heads.insert(name, LastTreeHead(state.tree_head, state.tree_root));
            }
            continue;
        }
        let label = label.unwrap().into_bytes();
        let proof = KtSearchResponse::decode(proof.as_slice()).unwrap();
        let head =
            FullTreeHead::decode(proof.tree_head.unwrap().encode_to_vec().as_slice()).unwrap();
        let condensed = CondensedTreeSearchResponse::decode(
            proof.condensed.unwrap().encode_to_vec().as_slice(),
        )
        .unwrap();
        let result = verifier.verify_search(
            SlimSearchRequest {
                search_key: label.clone(),
                version,
            },
            FullSearchResponse::new(condensed, &head),
            SearchContext {
                last_tree_head: last,
                last_distinguished_tree_head: distinguished,
                data: data.as_ref().map(|name| observations[name].1.clone()),
            },
            false,
            now,
        );
        if reject {
            assert!(result.is_err(), "{name} unexpectedly verified");
        } else {
            let result = result.unwrap_or_else(|error| panic!("{name}: {error}"));
            assert_eq!(result.value, bytes(&value.unwrap()), "{name}");
            let update = result.state_update;
            heads.insert(
                name.clone(),
                LastTreeHead(update.tree_head, update.tree_root),
            );
            observations.insert(name, (label, update.monitoring_data.unwrap()));
        }
    }
}
