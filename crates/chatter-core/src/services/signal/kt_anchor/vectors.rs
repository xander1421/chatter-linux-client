#[tokio::test(start_paused = true)]
async fn pin_retry_keeps_the_original_deadline() {
    let mut attempts = 0;
    let result = super::with_deadline(Duration::from_secs(10), async {
        attempts += 1;
        tokio::time::sleep(Duration::from_secs(6)).await;
        attempts += 1;
        tokio::time::sleep(Duration::from_secs(6)).await;
        Ok(())
    })
    .await;
    assert_eq!(attempts, 2);
    assert!(matches!(
        result,
        Err(KtError::Network(NetworkError::Timeout))
    ));
}

fn vector<'a>(vectors: &'a [Vector], name: &str) -> &'a Vector {
    vectors.iter().find(|vector| vector.name == name).unwrap()
}

fn search_proof(vectors: &[Vector], name: &str) -> KtSearchResponse {
    KtSearchResponse::decode(bytes(vector(vectors, name).proof.as_deref().unwrap()).as_slice())
        .unwrap()
}

fn monitor_proof(vectors: &[Vector], name: &str) -> (KtMonitorRequest, KtMonitorResponse) {
    let vector = vector(vectors, name);
    (
        KtMonitorRequest::decode(bytes(vector.monitor.as_deref().unwrap()).as_slice()).unwrap(),
        KtMonitorResponse::decode(bytes(vector.proof.as_deref().unwrap()).as_slice()).unwrap(),
    )
}

type SearchStep = (
    &'static [u8],
    Option<u64>,
    Option<u64>,
    Option<KtSearchResponse>,
);

#[derive(Default)]
struct Script {
    searches: VecDeque<SearchStep>,
    monitors: VecDeque<(KtMonitorRequest, Result<KtMonitorResponse, NetworkError>)>,
    stall: Option<tokio::sync::oneshot::Receiver<()>>,
}

impl KtTransport for Script {
    async fn search(
        &mut self,
        request: KtSearchRequest,
    ) -> Result<Option<KtSearchResponse>, NetworkError> {
        let (label, last, checkpoint, response) = self.searches.pop_front().unwrap();
        assert_eq!(request.search_key, label);
        let consistency = request.consistency.unwrap();
        assert_eq!(
            (consistency.last, consistency.distinguished),
            (last, checkpoint)
        );
        if let Some(stall) = self.stall.take() {
            stall.await.unwrap();
        }
        Ok(response)
    }

    async fn monitor(
        &mut self,
        request: KtMonitorRequest,
    ) -> Result<KtMonitorResponse, NetworkError> {
        let (expected, result) = self.monitors.pop_front().unwrap();
        assert_eq!(request, expected);
        result
    }
}

