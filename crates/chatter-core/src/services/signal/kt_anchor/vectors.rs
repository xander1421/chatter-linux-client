    client
        .monitors
        .push_back((request, Err(NetworkError::Unavailable)));
    assert!(matches!(
        check_own(&mut client, &settings, PEER, &key, &verifier, now).await,
        Err(KtError::Network(NetworkError::Unavailable))
    ));
