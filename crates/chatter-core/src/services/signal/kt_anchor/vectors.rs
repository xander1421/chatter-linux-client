#[derive(Deserialize)]
struct Vector {
    name: String,
    label: Option<String>,
    version: Option<u32>,
    last: Option<String>,
    distinguished: Option<String>,
    data: Option<String>,
    monitor: Option<String>,
    proof: Option<String>,
    value: Option<String>,
    #[serde(default)]
    reject: bool,
}

fn bytes(encoded: &str) -> Vec<u8> {
    base64::engine::general_purpose::STANDARD
        .decode(encoded)
        .unwrap()
}

