#[tokio::test]
async fn rejects_wrong_expected_value_tampering_rollback_and_invalid_reloaded_observations() {
    let (verifier, vectors, now) = fixtures();
    let (_dir, settings) = database();
    let mut client = Script {
        searches: [(
            b"distinguished".as_slice(),
            None,
            None,
            Some(search_proof(&vectors, "checkpoint 1")),
        )]
        .into(),
        ..Default::default()
    };
    let pin = Pin::load_at(&mut client, &settings, PinScope::Account, &verifier, now)
        .await
        .unwrap();
    let first = search_proof(&vectors, "first peer");
    let key = bytes(vector(&vectors, "first peer").value.as_deref().unwrap());
    assert!(pin.verify(PEER, first.clone(), b"wrong digest").is_err());
    let mut tampered = first.clone();
    tampered
        .tree_head
        .as_mut()
        .unwrap()
        .tree_head
        .as_mut()
        .unwrap()
        .signatures[0]
        .signature[0] ^= 1;
    assert!(pin.verify(PEER, tampered, &key).is_err());
    assert!(load_head(&settings, HEAD).unwrap().is_none());
    assert!(
        settings
            .get_string(&PinScope::Account.label_key("label", PEER))
            .unwrap()
            .is_none()
    );
    pin.verify(PEER, first.clone(), &key).unwrap();

    let pin = Pin::load_at(&mut client, &settings, PinScope::Account, &verifier, now)
        .await
        .unwrap();
    assert_eq!(
        pin.observations(PEER)
            .unwrap()
            .data
            .unwrap()
            .greatest_version(),
        0
    );
    let assert_history_unverified = |error| {
        assert!(matches!(
            crate::error::ServiceError::from(error),
            crate::error::ServiceError::Crypto(
                crate::error::CryptoError::KeyTransparencyHistoryUnverified
            )
        ));
    };
    assert_history_unverified(
        pin.verify(
            PEER,
            search_proof(&vectors, "signed same-size fork"),
            b"forked identity",
        )
        .unwrap_err(),
    );
    let other_key = bytes(vector(&vectors, "first other").value.as_deref().unwrap());
    let next = search_proof(&vectors, "first other");
    let mut altered_consistency = next.clone();
    altered_consistency.tree_head.as_mut().unwrap().last[0][0] ^= 1;
    assert_history_unverified(
        pin.verify(OTHER, altered_consistency, &other_key)
            .unwrap_err(),
    );
    pin.verify(OTHER, next, &other_key).unwrap();
    let pin = Pin::load_at(&mut client, &settings, PinScope::Account, &verifier, now)
        .await
        .unwrap();
    assert_history_unverified(pin.verify(PEER, first, &key).unwrap_err());
    assert_eq!(
        load_head(&settings, HEAD)
            .unwrap()
            .unwrap()
            .head
            .0
            .tree_size,
        3
    );

    let storage_key = PinScope::Account.label_key("label", PEER);
    let encoded = settings.get_string(&storage_key).unwrap().unwrap();
    let mut stored =
        super::StoredMonitoringData::decode(hex::decode(encoded).unwrap().as_slice()).unwrap();
    stored.ptrs.insert(3, 0);
    settings
        .set(&storage_key, &hex::encode(stored.encode_to_vec()))
        .unwrap();
    assert!(matches!(pin.observations(PEER), Err(KtError::Invalid(_))));
}

#[tokio::test]
async fn stalled_route_cannot_block_or_overwrite_a_faster_pin() {
    let (verifier, vectors, now) = fixtures();
    let (_dir, settings) = database();
    let mut bootstrap = Script {
        searches: [(
            b"distinguished".as_slice(),
            None,
            None,
            Some(search_proof(&vectors, "checkpoint 1")),
        )]
        .into(),
        ..Default::default()
    };
    Pin::load_at(&mut bootstrap, &settings, PinScope::Account, &verifier, now)
        .await
        .unwrap();
    let (release, halt) = tokio::sync::oneshot::channel();
    let first = search_proof(&vectors, "first peer");
    let mut slow = Script {
        searches: [(PEER, None, Some(1), Some(first.clone()))].into(),
        stall: Some(halt),
        ..Default::default()
    };
    let mut fast = Script {
        searches: [(PEER, None, Some(1), Some(first))].into(),
        ..Default::default()
    };
    let (slow, ()) = tokio::join!(
        search_contact(&mut slow, &settings, PinScope::Account, PEER, &verifier, now),
        async {
            let value = tokio::time::timeout(
                Duration::from_secs(2),
                search_contact(&mut fast, &settings, PinScope::Account, PEER, &verifier, now),
            )
            .await
            .unwrap()
            .unwrap();
            assert!(value.is_some());
            assert_eq!(
                load_head(&settings, HEAD)
                    .unwrap()
                    .unwrap()
                    .head
                    .0
                    .tree_size,
                2
            );
            release.send(()).unwrap();
        },
    );
    assert!(matches!(slow, Err(KtError::PinChanged)));
}

