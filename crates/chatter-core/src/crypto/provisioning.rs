//! Device provisioning envelope encryption.
//!
//! Implements Signal-style provisioning envelope cryptography for linking new
//! devices to an existing account.
//!
//! # Wire format (`ProvisionEnvelope`)
//!
//! Matches the Signal `ProvisioningCipher` byte structure (with our own HKDF
//! info string for domain separation):
//!
//! - `public_key`: primary device's ephemeral X25519 key, **33 bytes**:
//!   `DJB_TYPE (0x05) || raw_32_byte_pub`.
//! - `body`: `VERSION (0x01) || IV (16) || AES-256-CBC ciphertext || HMAC-SHA256 (32)`.
//!
//! Adopting Signal's byte layout (version byte, 0x05 pubkey prefix, MAC over
//! `version || iv || ct`) keeps the construction auditable against the
//! reference Signal `ProvisioningCipher` even though we're not wire-compatible
//! with Signal servers.
//!
//! # Key schedule
//!
//! ```text
//! shared       = X25519(my_priv, peer_pub)
//! okm[64]      = HKDF-SHA256(IKM=shared, salt=[], info="Chatter Provisioning Message", L=64)
//! aes_key[32]  = okm[0..32]
//! mac_key[32]  = okm[32..64]
//! ```
//!
//! `hkdf::Hkdf::new(None, _)` substitutes a 32-byte zero salt per RFC 5869 §2.2,
//! matching Signal's explicit `new byte[32]` salt.
//!
//! # Roles
//!
//! - **New device**: generates an ephemeral X25519 keypair, embeds its public
//!   half in the QR code, then [`decrypt_envelope`] when the primary uploads
//!   the encrypted `ProvisionMessage`.
//! - **Primary device**: parses the new device's ephemeral public key from the
//!   QR payload, builds a [`ProvisionMessage`] from local identity/profile
//!   state, and calls [`encrypt_envelope`] before uploading.

use aes::cipher::{
    block_padding::Pkcs7, BlockDecryptMut, BlockEncryptMut, KeyIvInit,
};
use hkdf::Hkdf;
use hmac::{Hmac, Mac};
use prost::Message;
use rand_core_06::OsRng;
use sha2::Sha256;
use subtle::ConstantTimeEq;
use x25519_dalek::{PublicKey, StaticSecret};
use zeroize::Zeroizing;

use crate::error::CryptoError;
use crate::proto::provisioning_v1::{ProvisionEnvelope, ProvisionMessage};

type Aes256CbcEnc = cbc::Encryptor<aes::Aes256>;
type Aes256CbcDec = cbc::Decryptor<aes::Aes256>;
type HmacSha256 = Hmac<Sha256>;

const IV_LEN: usize = 16;
const MAC_LEN: usize = 32;
const AES_KEY_LEN: usize = 32;
const MAC_KEY_LEN: usize = 32;
const PUB_LEN: usize = 32;
/// Signal's DJB_TYPE prefix marking a Curve25519/X25519 public key.
const DJB_TYPE: u8 = 0x05;
const PUB_LEN_PREFIXED: usize = 1 + PUB_LEN;
/// Provisioning protocol version.
const VERSION: u8 = 0x01;
const VERSION_LEN: usize = 1;
const HKDF_INFO: &[u8] = b"Chatter Provisioning Message";
const MIN_BODY_LEN: usize = VERSION_LEN + IV_LEN + 16 + MAC_LEN; // version + IV + one AES block + MAC

/// Ephemeral X25519 keypair for one provisioning session.
///
/// Generated by the new device, exposed in QR payload, kept in memory until
/// the envelope arrives. Private half zeroized on drop via `StaticSecret`.
pub struct ProvisioningKeypair {
    secret: StaticSecret,
    public: [u8; PUB_LEN],
}

impl ProvisioningKeypair {
    /// Generate a fresh ephemeral keypair.
    pub fn generate() -> Self {
        let secret = StaticSecret::random_from_rng(OsRng);
        let public = PublicKey::from(&secret).to_bytes();
        Self { secret, public }
    }

    /// Reconstruct from raw 32-byte secret. For session restore in case the UI
    /// flow needs to outlive a single in-memory object.
    pub fn from_secret_bytes(bytes: &[u8; 32]) -> Self {
        let secret = StaticSecret::from(*bytes);
        let public = PublicKey::from(&secret).to_bytes();
        Self { secret, public }
    }

    pub fn public_bytes(&self) -> [u8; PUB_LEN] {
        self.public
    }

    pub fn secret_bytes(&self) -> [u8; 32] {
        self.secret.to_bytes()
    }
}

/// Encrypt a `ProvisionMessage` for the new device.
///
/// Generates a fresh ephemeral X25519 keypair, performs ECDH against
/// `recipient_pub` (the new device's raw 32-byte X25519 key), derives keys
/// via HKDF, then encrypts with AES-256-CBC and authenticates with
/// HMAC-SHA256 over `version || iv || ciphertext`.
///
/// `recipient_pub` is the raw 32-byte key — callers strip the `0x05` DJB
/// prefix before invocation. The returned envelope embeds our own ephemeral
/// public with the `0x05` prefix per Signal convention.
pub fn encrypt_envelope(
    recipient_pub: &[u8; PUB_LEN],
    message: &ProvisionMessage,
) -> Result<ProvisionEnvelope, CryptoError> {
    let ephemeral = StaticSecret::random_from_rng(OsRng);
    let ephemeral_pub = PublicKey::from(&ephemeral).to_bytes();

    let peer = PublicKey::from(*recipient_pub);
    let shared_secret = ephemeral.diffie_hellman(&peer);

    // RFC 7748 §6.1: reject low-order recipient keys that collapse ECDH to a
    // constant. Without this gate an attacker-supplied low-order key forces a
    // predictable provisioning key.
    if !shared_secret.was_contributory() {
        return Err(CryptoError::KeyDerivationFailed(
            "non-contributory ECDH (low-order public key)".into(),
        ));
    }

    let shared = Zeroizing::new(shared_secret.to_bytes());

    let (aes_key, mac_key) = derive_keys(&shared)?;

    let mut iv = [0u8; IV_LEN];
    {use rand::TryRngCore; rand::rngs::OsRng.try_fill_bytes(&mut iv).expect("OS CSPRNG must not fail");}

    // Carries the identity private key.
    let plaintext = Zeroizing::new(message.encode_to_vec());
    let ct = Aes256CbcEnc::new(aes_key.as_ref().into(), (&iv).into())
        .encrypt_padded_vec_mut::<Pkcs7>(&plaintext);

    let mut mac = HmacSha256::new_from_slice(mac_key.as_ref())
        .map_err(|e| CryptoError::EncryptionFailed(format!("HMAC init: {e}")))?;
    mac.update(&[VERSION]);
    mac.update(&iv);
    mac.update(&ct);
    let tag = mac.finalize().into_bytes();

    let mut body = Vec::with_capacity(VERSION_LEN + IV_LEN + ct.len() + MAC_LEN);
    body.push(VERSION);
    body.extend_from_slice(&iv);
    body.extend_from_slice(&ct);
    body.extend_from_slice(&tag);

    let mut prefixed_pub = Vec::with_capacity(PUB_LEN_PREFIXED);
    prefixed_pub.push(DJB_TYPE);
    prefixed_pub.extend_from_slice(&ephemeral_pub);

    Ok(ProvisionEnvelope {
        public_key: prefixed_pub,
        body,
    })
}

/// Decrypt a `ProvisionEnvelope` received from the primary device.
///
/// Verifies the MAC in constant time before attempting CBC decryption to
/// avoid padding-oracle leakage. On any failure the function returns a
/// generic [`CryptoError::DecryptionFailed`] without leaking position.
pub fn decrypt_envelope(
    my_keypair: &ProvisioningKeypair,
    envelope: &ProvisionEnvelope,
) -> Result<ProvisionMessage, CryptoError> {
    if envelope.public_key.len() != PUB_LEN_PREFIXED {
        return Err(CryptoError::InvalidKeyLength {
            expected: PUB_LEN_PREFIXED,
            got: envelope.public_key.len(),
        });
    }
    if envelope.public_key[0] != DJB_TYPE {
        return Err(CryptoError::InvalidKey(format!(
            "unexpected key type prefix: 0x{:02x}",
            envelope.public_key[0]
        )));
    }
    if envelope.body.len() < MIN_BODY_LEN {
        return Err(CryptoError::DecryptionFailed(
            "envelope body too short".into(),
        ));
    }
    if envelope.body[0] != VERSION {
        return Err(CryptoError::DecryptionFailed(format!(
            "unsupported provisioning version: 0x{:02x}",
            envelope.body[0]
        )));
    }
    let ct_len = envelope.body.len() - VERSION_LEN - IV_LEN - MAC_LEN;
    if ct_len == 0 || ct_len % 16 != 0 {
        return Err(CryptoError::DecryptionFailed(
            "envelope ciphertext not block-aligned".into(),
        ));
    }

    let mut peer_bytes = [0u8; PUB_LEN];
    peer_bytes.copy_from_slice(&envelope.public_key[1..]);
    let peer = PublicKey::from(peer_bytes);
    let shared_secret = my_keypair.secret.diffie_hellman(&peer);

    // RFC 7748 §6.1: reject low-order sender keys that collapse ECDH to a
    // constant. Without this gate an attacker can force a predictable
    // decryption key with a low-order envelope public key.
    if !shared_secret.was_contributory() {
        return Err(CryptoError::DecryptionFailed(
            "non-contributory ECDH (low-order public key)".into(),
        ));
    }

    let shared = Zeroizing::new(shared_secret.to_bytes());

    let (aes_key, mac_key) = derive_keys(&shared)?;

    let version = &envelope.body[..VERSION_LEN];
    let iv = &envelope.body[VERSION_LEN..VERSION_LEN + IV_LEN];
    let ct = &envelope.body[VERSION_LEN + IV_LEN..VERSION_LEN + IV_LEN + ct_len];
    let received_mac = &envelope.body[VERSION_LEN + IV_LEN + ct_len..];

    let mut mac = HmacSha256::new_from_slice(mac_key.as_ref())
        .map_err(|e| CryptoError::DecryptionFailed(format!("HMAC init: {e}")))?;
    mac.update(version);
    mac.update(iv);
    mac.update(ct);
    let expected_tag = mac.finalize().into_bytes();

    if expected_tag.ct_eq(received_mac).unwrap_u8() != 1 {
        return Err(CryptoError::DecryptionFailed("MAC mismatch".into()));
    }

    // Decrypted in place: ends up holding the identity private key.
    let mut buf = Zeroizing::new(ct.to_vec());
    let plaintext = Aes256CbcDec::new(aes_key.as_ref().into(), iv.into())
        .decrypt_padded_mut::<Pkcs7>(&mut buf)
        .map_err(|_| CryptoError::DecryptionFailed("AES-CBC unpad".into()))?;

    ProvisionMessage::decode(plaintext)
        .map_err(|e| CryptoError::DecryptionFailed(format!("proto decode: {e}")))
}

fn derive_keys(
    shared: &[u8; 32],
) -> Result<(Zeroizing<[u8; AES_KEY_LEN]>, Zeroizing<[u8; MAC_KEY_LEN]>), CryptoError> {
    let hk = Hkdf::<Sha256>::new(None, shared);
    let mut okm = Zeroizing::new([0u8; AES_KEY_LEN + MAC_KEY_LEN]);
    hk.expand(HKDF_INFO, okm.as_mut())
        .map_err(|e| CryptoError::KeyDerivationFailed(format!("HKDF expand: {e}")))?;

    let mut aes_key = Zeroizing::new([0u8; AES_KEY_LEN]);
    let mut mac_key = Zeroizing::new([0u8; MAC_KEY_LEN]);
    aes_key.copy_from_slice(&okm[..AES_KEY_LEN]);
    mac_key.copy_from_slice(&okm[AES_KEY_LEN..]);
    Ok((aes_key, mac_key))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_message() -> ProvisionMessage {
        ProvisionMessage {
            aci_identity_key_private: vec![0x11; 32],
            pni_identity_key_private: vec![],
            aci: "00000000-0000-0000-0000-000000000001".into(),
            pni: String::new(),
            number: String::new(),
            provisioning_code: "test-code-12345".into(),
            profile_key: vec![0x22; 32],
            master_key: vec![],
            read_receipts: true,
            typing_indicators: true,
            provisioning_user_agent: "linux-client/0.1".into(),
            primary_device_registration_id: 1234,
            ephemeral_backup_key: None,
            svr_salt_username: "alice".into(),
            full_username: "alice.1234".into(),
        }
    }

    #[test]
    fn roundtrip_succeeds() {
        let new_device = ProvisioningKeypair::generate();
        let msg = sample_message();

        let envelope = encrypt_envelope(&new_device.public_bytes(), &msg).expect("encrypt");
        let decoded = decrypt_envelope(&new_device, &envelope).expect("decrypt");

        assert_eq!(decoded.aci, msg.aci);
        assert_eq!(decoded.provisioning_code, msg.provisioning_code);
        assert_eq!(decoded.profile_key, msg.profile_key);
        assert_eq!(decoded.aci_identity_key_private, msg.aci_identity_key_private);
        assert_eq!(
            decoded.primary_device_registration_id,
            msg.primary_device_registration_id
        );
    }

    #[test]
    fn wrong_recipient_key_fails() {
        let intended = ProvisioningKeypair::generate();
        let attacker = ProvisioningKeypair::generate();

        let envelope =
            encrypt_envelope(&intended.public_bytes(), &sample_message()).expect("encrypt");

        let err = decrypt_envelope(&attacker, &envelope).expect_err("must reject");
        match err {
            CryptoError::DecryptionFailed(_) => {}
            other => panic!("expected DecryptionFailed, got {other:?}"),
        }
    }

    #[test]
    fn tampered_ciphertext_fails() {
        let new_device = ProvisioningKeypair::generate();
        let mut envelope =
            encrypt_envelope(&new_device.public_bytes(), &sample_message()).expect("encrypt");

        // Flip a byte inside the ciphertext (after version + IV, before MAC).
        let mid = VERSION_LEN + IV_LEN + 4;
        envelope.body[mid] ^= 0x01;

        let err = decrypt_envelope(&new_device, &envelope).expect_err("must reject");
        match err {
            CryptoError::DecryptionFailed(_) => {}
            other => panic!("expected DecryptionFailed, got {other:?}"),
        }
    }

    #[test]
    fn tampered_version_byte_fails() {
        let new_device = ProvisioningKeypair::generate();
        let mut envelope =
            encrypt_envelope(&new_device.public_bytes(), &sample_message()).expect("encrypt");
        envelope.body[0] = 0x02; // bogus version
        let err = decrypt_envelope(&new_device, &envelope).expect_err("must reject");
        assert!(matches!(err, CryptoError::DecryptionFailed(_)));
    }

    #[test]
    fn missing_djb_prefix_rejected() {
        let new_device = ProvisioningKeypair::generate();
        let mut envelope =
            encrypt_envelope(&new_device.public_bytes(), &sample_message()).expect("encrypt");
        envelope.public_key[0] = 0x04; // wrong type prefix
        let err = decrypt_envelope(&new_device, &envelope).expect_err("must reject");
        assert!(matches!(err, CryptoError::InvalidKey(_)));
    }

    #[test]
    fn envelope_format_constants() {
        let new_device = ProvisioningKeypair::generate();
        let envelope =
            encrypt_envelope(&new_device.public_bytes(), &sample_message()).expect("encrypt");
        // 33-byte prefixed pubkey (0x05 || 32B)
        assert_eq!(envelope.public_key.len(), PUB_LEN_PREFIXED);
        assert_eq!(envelope.public_key[0], DJB_TYPE);
        // body starts with version 0x01
        assert_eq!(envelope.body[0], VERSION);
        // body = version(1) + IV(16) + ct(>=16) + mac(32), all ct blocks are 16
        let body_overhead = VERSION_LEN + IV_LEN + MAC_LEN;
        let ct_len = envelope.body.len() - body_overhead;
        assert!(ct_len >= 16 && ct_len % 16 == 0);
    }

    #[test]
    fn tampered_mac_fails() {
        let new_device = ProvisioningKeypair::generate();
        let mut envelope =
            encrypt_envelope(&new_device.public_bytes(), &sample_message()).expect("encrypt");

        let last = envelope.body.len() - 1;
        envelope.body[last] ^= 0xff;

        let err = decrypt_envelope(&new_device, &envelope).expect_err("must reject");
        assert!(matches!(err, CryptoError::DecryptionFailed(_)));
    }

    #[test]
    fn wrong_pubkey_length_rejected() {
        let new_device = ProvisioningKeypair::generate();
        let mut envelope =
            encrypt_envelope(&new_device.public_bytes(), &sample_message()).expect("encrypt");
        envelope.public_key.push(0); // 34 bytes now
        let err = decrypt_envelope(&new_device, &envelope).expect_err("must reject");
        assert!(matches!(err, CryptoError::InvalidKeyLength { .. }));
    }

    #[test]
    fn truncated_body_rejected() {
        let new_device = ProvisioningKeypair::generate();
        let mut envelope =
            encrypt_envelope(&new_device.public_bytes(), &sample_message()).expect("encrypt");
        envelope.body.truncate(MIN_BODY_LEN - 1);
        let err = decrypt_envelope(&new_device, &envelope).expect_err("must reject");
        assert!(matches!(err, CryptoError::DecryptionFailed(_)));
    }

    #[test]
    fn keypair_secret_roundtrip() {
        let kp = ProvisioningKeypair::generate();
        let bytes = kp.secret_bytes();
        let restored = ProvisioningKeypair::from_secret_bytes(&bytes);
        assert_eq!(kp.public_bytes(), restored.public_bytes());
    }
}
